import crypto from "node:crypto";
import { callLLM, getProviderHealth } from "./llm.js";
import { fetchIssuePlanningContext, formatPlanningContext } from "./github.js";
import { buildIssuePlanPrompt } from "./prompts.js";

const MAX = 12000;
const list = (value) => Array.isArray(value) ? value.filter((item) => typeof item === "string").map((item) => item.slice(0, 1000)).slice(0, 12) : [];
const text = (value, fallback = "") => typeof value === "string" ? value.slice(0, MAX) : fallback;
const meaningfulText = (value) => typeof value === "string" && value.trim().length > 0;
const meaningfulList = (value) => Array.isArray(value) && value.some((item) => meaningfulText(item));

export function issueRevision(issue = {}) {
  return crypto.createHash("sha256").update(JSON.stringify({ id: issue.id || issue.number, updatedAt: issue.updatedAt, title: issue.title, body: issue.body })).digest("hex").slice(0, 24);
}

export function normalizeIssuePlan(value, metadata = {}) {
  let item = value;
  if (typeof item === "string") {
    try { item = JSON.parse(item.replace(/^```json\s*|```$/g, "").trim()); } catch { throw new Error("INVALID_PLAN_JSON"); }
  }
  if (!item || typeof item !== "object" || Array.isArray(item)) throw new Error("INVALID_PLAN_JSON");
  if (!meaningfulText(item.summary) || !meaningfulList(item.implementationSteps) || !meaningfulList(item.testPlan)) throw new Error("INVALID_PLAN_OUTPUT");
  const confidence = ["low", "medium", "high"].includes(String(item.confidence).toLowerCase()) ? String(item.confidence).toLowerCase() : "low";
  return {
    summary: text(item.summary, "No summary was generated."),
    understanding: text(item.understanding, "The issue could not be fully interpreted from available evidence."),
    affectedFiles: Array.isArray(item.affectedFiles) ? item.affectedFiles.slice(0, 30).map((file) => ({ path: text(file?.path, "unknown"), reason: text(file?.reason), plannedChange: text(file?.plannedChange) })) : [],
    implementationSteps: list(item.implementationSteps),
    testPlan: list(item.testPlan),
    risks: list(item.risks),
    assumptions: list(item.assumptions),
    confidence,
    provider: metadata.provider || null,
    model: metadata.model || null,
    issueRevision: metadata.issueRevision || null,
    repository: metadata.repository || null,
    issueNumber: metadata.issueNumber || null,
    issueTitle: metadata.issueTitle || null,
    issueUrl: metadata.issueUrl || null,
    createdAt: metadata.createdAt || new Date().toISOString(),
  };
}

export function selectedProviderMetadata() {
  const selected = Object.values(getProviderHealth()).find((item) => item.selectedModel);
  return { provider: selected?.provider || null, model: selected?.selectedModel || null };
}

export async function createIssuePlan({ octokit, owner, repo, issueNumber, deliveryId, logger = () => {} }) {
  const context = await fetchIssuePlanningContext({ octokit, owner, repo, issueNumber });
  const revision = issueRevision(context.issue);
  let invocationMetadata = null;
  const content = await callLLM([{ role: "user", content: buildIssuePlanPrompt(formatPlanningContext(context, 12000)) }], { temperature: 0.1, top_p: 0.8, max_tokens: 1400, totalTimeoutMs: 30000, enableThinking: false, providerTimeoutMs: 16000, responseFormat: { type: "json_object" }, errorLogger: logger, task: "issue_plan", onInvocation: (metadata) => { invocationMetadata = metadata; } });
  const metadata = { ...(invocationMetadata || selectedProviderMetadata()), issueRevision: revision, repository: context.repository.fullName, issueNumber: context.issue.number, issueTitle: context.issue.title, issueUrl: context.issue.htmlUrl, deliveryId };
  return normalizeIssuePlan(content, metadata);
}

export function renderIssuePlanMarkdown(plan = {}) {
  const files = (plan.affectedFiles || []).map((file) => `- \`${file.path}\` — ${file.reason}${file.plannedChange ? ` Planned change: ${file.plannedChange}` : ""}`).join("\n") || "- No specific files identified.";
  const bullets = (items, fallback) => items?.length ? items.map((item, index) => `${index + 1}. ${item}`).join("\n") : fallback;
  return `<!-- ai-agentrouter:issue-plan:${plan.issueRevision || "unknown"} -->\n## PRISM implementation plan\n\n### Summary\n${plan.summary}\n\n### Understanding\n${plan.understanding}\n\n### Affected files\n${files}\n\n### Steps\n${bullets(plan.implementationSteps, "No implementation steps returned.")}\n\n### Tests\n${bullets(plan.testPlan, "No test plan returned.")}\n\n### Risks\n${bullets(plan.risks, "No risks returned.")}\n\n### Assumptions\n${bullets(plan.assumptions, "No assumptions returned.")}\n\n### Confidence\n${String(plan.confidence || "low").replace(/^./, (value) => value.toUpperCase())}\n\nGenerated by PRISM using ${plan.provider || "unavailable"}/${plan.model || "unavailable"}.`;
}
